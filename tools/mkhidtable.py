#!/usr/bin/env python3
"""USB HID usage -> PC scancode (set 1) table for rtl/kbd_ch9350.sv.
One byte per usage: bit 7 = E0 prefix, bits 6-0 = make code, 00 = no key."""
import sys
t = [0] * 256
def put(usage, code, ext=False): t[usage] = code | (0x80 if ext else 0)
letters = dict(a=0x1E, b=0x30, c=0x2E, d=0x20, e=0x12, f=0x21, g=0x22, h=0x23, i=0x17, j=0x24, k=0x25,
               l=0x26, m=0x32, n=0x31, o=0x18, p=0x19, q=0x10, r=0x13, s=0x1F, t=0x14, u=0x16, v=0x2F,
               w=0x11, x=0x2D, y=0x15, z=0x2C)
for ch, code in letters.items(): put(0x04 + ord(ch) - ord('a'), code)
for i in range(10): put(0x1E + i, 0x02 + i)                       # 1..9, 0
for u, c in {0x28: 0x1C, 0x29: 0x01, 0x2A: 0x0E, 0x2B: 0x0F, 0x2C: 0x39, 0x2D: 0x0C, 0x2E: 0x0D,
             0x2F: 0x1A, 0x30: 0x1B, 0x31: 0x2B, 0x32: 0x2B, 0x33: 0x27, 0x34: 0x28, 0x35: 0x29,
             0x36: 0x33, 0x37: 0x34, 0x38: 0x35, 0x39: 0x3A, 0x44: 0x57, 0x45: 0x58, 0x47: 0x46,
             0x53: 0x45, 0x55: 0x37, 0x56: 0x4A, 0x57: 0x4E, 0x62: 0x52, 0x63: 0x53, 0x64: 0x56}.items():
    put(u, c)
for i in range(10): put(0x3A + i, 0x3B + i)                       # F1..F10
for i, c in enumerate([0x4F, 0x50, 0x51, 0x4B, 0x4C, 0x4D, 0x47, 0x48, 0x49]): put(0x59 + i, c)  # keypad 1..9
for u, c in {0x46: 0x37, 0x49: 0x52, 0x4A: 0x47, 0x4B: 0x49, 0x4C: 0x53, 0x4D: 0x4F, 0x4E: 0x51,
             0x4F: 0x4D, 0x50: 0x4B, 0x51: 0x50, 0x52: 0x48, 0x54: 0x35, 0x58: 0x1C, 0x65: 0x5D}.items():
    put(u, c, True)
# modifiers, at usages E0..E7 as in the HID tables (the decoder looks them up there)
for i, (c, e) in enumerate([(0x1D, 0), (0x2A, 0), (0x38, 0), (0x5B, 1), (0x1D, 1), (0x36, 0), (0x38, 1), (0x5C, 1)]):
    put(0xE0 + i, c, bool(e))
open(sys.argv[1], 'w').write('\n'.join('%02x' % b for b in t) + '\n')
